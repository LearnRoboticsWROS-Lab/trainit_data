"""The recorder's EXPORTED recording vocabulary (D0.8): what a ``trainit-recording/1.0`` author may write.

A configuration tool (TSA) validates the recording configuration it authors BEFORE generation, against a snapshot of
this file pinned by its catalog (ADR-0021) -- it never imports this package. The file is GENERATED from the parser's
own constants (``recording_config``, ``execution_triggers``, ``contract``) and the core vocabulary, and a test fails
whenever the committed file and the code disagree::

    python3 -m trainit_data_ros.recording_vocabulary --write    # regenerate catalog/recording_vocabulary.yaml
    python3 -m trainit_data_ros.recording_vocabulary --check    # exit 1 if the committed file is stale

It states facts the parser enforces; the parser stays the authority (a configuration that passes a consumer's
snapshot check is still validated by the recorder at start-up). No ROS imports.
"""
import argparse
import sys
from pathlib import Path

from trainit_data import _strict as s          # same repository, same version line (ADR-0029 Decision 1)
from trainit_data.session_record import CLASSIFICATIONS
from trainit_data.vocab import Vocabulary

from . import __version__
from .contract import CAMERA_STREAMS
from .execution_triggers import EDGES, PHASES, TRANSITIONS
from .recording_config import (DEFAULT_POLICY, DEFAULTS, IMPLEMENTED_POLICIES, IMPLEMENTED_TRIGGERS, LIMITS,
                               SCHEMA_MAJOR, SCHEMA_NAME)

SCHEMA = 'trainit-recording-vocabulary/1.0'
FILE = Path(__file__).resolve().parents[1] / 'catalog' / 'recording_vocabulary.yaml'
HEADER = ('# GENERATED by `python3 -m trainit_data_ros.recording_vocabulary --write` from the recorder\'s parser\n'
          '# constants: do not edit. A test fails when this file and the code disagree (D0.8).\n')


def vocabulary(vocab: Vocabulary = None) -> dict:
    """The exported vocabulary (JSON-plain, deterministic)."""
    vocab = vocab or Vocabulary.default()
    return {
        'schema': SCHEMA,
        'trainit_data_ros': __version__,
        'recording_schema': f'{SCHEMA_NAME}/{SCHEMA_MAJOR}.0',
        'identifier_pattern': s.IDENT_RE.pattern,
        # 'replay' is a data source of the recorder itself (a sealed session), never a deployment's camera backend
        'backends': [b for b in vocab.rows('backends') if b != 'replay'],
        'sim_sources': list(vocab.rows('sim_sources')),
        'classifications': sorted(CLASSIFICATIONS),
        'streams': {name: {'modality': row[2], 'registered_to': row[4]} for name, row in CAMERA_STREAMS.items()},
        'triggers': {
            'kinds': list(IMPLEMENTED_TRIGGERS),
            'max_per_kind': {'MANUAL': 1},
            'fields': {
                'MANUAL': {},
                'INTERVAL': {'period_ms': {'type': 'int', 'min': 1, 'required': True},
                             'max_captures': {'type': 'int', 'min': 1, 'required': False}},
                'EVENT': {'process_channel': {'type': 'identifier', 'required': True},
                          'edge': {'type': 'enum', 'values': list(EDGES), 'required': True}},
                'APPLICATION_STATE': {'task': {'type': 'identifier', 'required': True},
                                      'step': {'type': 'identifier', 'required': False},
                                      'transition': {'type': 'enum', 'values': list(TRANSITIONS), 'required': True},
                                      'context': {'type': 'pick_attempt', 'required': False}},
            },
            # a pick-attempt context names a STEP; its phase fixes the transitions it may fire on
            'pick_attempt_phases': {phase: list(transitions) for phase, transitions in PHASES.items()},
        },
        'sync': {'policies': [{'name': n, 'version': v} for n, v in sorted(IMPLEMENTED_POLICIES)],
                 'fields': {'tolerance_ms': {'type': 'float', 'min_exclusive': 0, 'required': False},
                            'timeout_ms': {'type': 'int', 'min': 1, 'required': False}},
                 # the policy a configuration that names none should get (a consumer never relies on list order)
                 'defaults': {'policy': {'name': DEFAULT_POLICY[0], 'version': DEFAULT_POLICY[1]},
                              'timeout_ms': DEFAULTS['timeout_ms'],
                              'tolerance_ms': 'half the frame period of the slowest stream (hardware profile)'}},
        'writer': {'defaults': {k: DEFAULTS[k] for k in LIMITS}, 'limits': dict(LIMITS)},
    }


def render(vocab: Vocabulary = None) -> str:
    import yaml
    return HEADER + yaml.safe_dump(vocabulary(vocab), sort_keys=True, default_flow_style=False, width=100)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--write', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        FILE.parent.mkdir(exist_ok=True)
        FILE.write_text(text)
        return 0
    if not FILE.is_file() or FILE.read_text() != text:
        print(f'{FILE} is stale: run python3 -m trainit_data_ros.recording_vocabulary --write', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':      # pragma: no cover
    sys.exit(main())
